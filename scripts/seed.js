/**
 * Demo data loader.
 *   npm run seed                 insert demo rows into Supabase (uses .env)
 *   npm run seed -- --clean      delete demo rows again
 *   npm run seed -- --sql        (re)write supabase/seed.sql, to paste into the Supabase SQL Editor
 */
import fs from "fs";
import { buildRows } from "./mock-data.js";
import { buildRealRows } from "./real-data.js";

// --real: genuine articles + hand-made extraction (see real-data.js); default: fictional demo data
const real = process.argv.includes("--real");
const arg = process.argv.slice(2).find((a) => a !== "--real");
const rows = real ? buildRealRows() : buildRows();
const marker = real ? "sample" : "mock";
const markerVal = real ? "real" : "true";
const sqlFile = real ? "supabase/seed_real.sql" : "supabase/seed.sql";

const q = (s) => (s == null ? "NULL" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => (a.length ? `ARRAY[${a.map(q).join(",")}]::text[]` : "'{}'::text[]");
const json = (o) => `${q(JSON.stringify(o))}::jsonb`;

if (arg === "--sql") {
  const cols = "title,summary,short_tag,impact_score,original_url,source_name,source_kind,published_at,title_uk,summary_uk,event_type,entities,stack_tags,cve_ids,score_breakdown,meta,event_id";
  const values = rows.map((r) => `(${[
    q(r.title), q(r.summary), q(r.short_tag), r.impact_score, q(r.original_url), q(r.source_name), q(r.source_kind),
    r.published_at ? `${q(r.published_at)}::timestamptz` : `now() - interval '${r.published_ago_min} minutes'`, q(r.title_uk), q(r.summary_uk), q(r.event_type),
    json(r.entities), arr(r.stack_tags), arr(r.cve_ids), json(r.score_breakdown), json(r.meta), `${q(r.event_id)}::uuid`,
  ].join(", ")})`);
  const sql = `-- Defrag ${real ? "sample data: REAL articles, extraction done by hand" : "demo data (FICTIONAL, not real news)"}. Generated by scripts/seed.js; safe to run more than once.
-- Run AFTER supabase/migrations/002_context_hub.sql.
-- Remove later with:  DELETE FROM defrag_articles WHERE meta->>'${marker}' = '${markerVal}';

INSERT INTO defrag_articles (${cols})
VALUES
${values.join(",\n")}
${real ? `ON CONFLICT (original_url) DO UPDATE SET\n${cols.split(",").filter((c) => c !== "original_url").map((c) => `  ${c} = EXCLUDED.${c}`).join(",\n")};` : "ON CONFLICT (original_url) DO NOTHING;"}
`;
  fs.writeFileSync(sqlFile, sql);
  console.log(`Wrote ${sqlFile} (${rows.length} articles, ${new Set(rows.map((r) => r.event_id)).size} events)`);
  process.exit(0);
}

const { supabase } = await import("../server/db.js");
if (!supabase) {
  console.error("Supabase is not configured (see .env.example). Use `npm run seed -- --sql` and paste supabase/seed.sql into the SQL Editor instead.");
  process.exit(1);
}

if (arg === "--clean") {
  const { error, count } = await supabase.from("defrag_articles").delete({ count: "exact" }).eq(`meta->>${marker}`, markerVal);
  if (error) throw new Error(error.message);
  console.log(`Deleted ${count ?? "?"} demo rows`);
  process.exit(0);
}

const now = Date.now();
const payload = rows.map(({ published_ago_min, ...r }) => ({ ...r, published_at: r.published_at ?? new Date(now - published_ago_min * 60000).toISOString() }));
let inserted = 0;
for (let i = 0; i < payload.length; i += 40) {
  const { data, error } = await supabase.from("defrag_articles").upsert(payload.slice(i, i + 40), { onConflict: "original_url", ignoreDuplicates: !real }).select("id");
  if (error) throw new Error(error.message);
  inserted += data?.length ?? 0;
}
console.log(`Seeded ${inserted} new demo articles (${payload.length - inserted} already existed).`);
